-- Test-only pre-V2 schema. Production schema changes are applied separately.
-- Priority and parse evidence must be added by the real V2 and V3 scripts.
CREATE TABLE jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_email VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    cpu_hours DOUBLE PRECISION NOT NULL DEFAULT 0,
    gpu_hours DOUBLE PRECISION NOT NULL DEFAULT 0,
    original_start_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    deadline TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    flexibility_window_hours INTEGER NOT NULL DEFAULT 0,
    is_exempt_from_rescheduling BOOLEAN NOT NULL DEFAULT FALSE,
    raw_constraints VARCHAR(1000),
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE INDEX idx_jobs_owner_start ON jobs (owner_email, original_start_time);
CREATE INDEX idx_jobs_owner_deadline ON jobs (owner_email, deadline);
